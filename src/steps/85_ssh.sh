#!/usr/bin/env bash
#
# sshd MACs.  Stock OpenSSH still offers hmac-sha1 and the 64-bit-tag umac-64
# MACs, which a penetration test reports as "SSH Legacy or Short-Tag MAC
# Algorithms Supported", so restrict sshd to SSHD_MACS with a drop-in.  Unlike
# the firewall this runs by default (opt out with --skip-ssh-hardening): current
# clients prefer an AEAD cipher (chacha20-poly1305, AES-GCM) that carries no
# separate MAC, and the drop-in is checked with `sshd -t` before sshd reloads.

step_ssh() {
    if [[ "${SKIP_SSH_HARDENING}" == "1" ]]; then
        skipped "sshd MACs left as shipped (--skip-ssh-hardening)"
        return 0
    fi
    if ! cmd_exists sshd; then
        notice "sshd not installed; nothing to harden."
        return 0
    fi

    write_file "${SSHD_DROPIN}" 0644 root:root <<EOF
# Generated by session-fileserver-setup ${INSTALLER_VERSION}.
# Encrypt-then-MAC SHA-2 / UMAC-128 only: no hmac-sha1, no 64-bit-tag umac-64.
MACs ${SSHD_MACS}
EOF
    if [[ "${DRY_RUN}" == "1" ]]; then
        printf '    %s[dry-run]%s sshd -t && systemctl try-reload-or-restart ssh\n' "${C_DIM}" "${C_RESET}"
        return 0
    fi

    # sshd -t / -T need the privilege-separation directory, which systemd only
    # creates while ssh.service runs; under socket activation (Ubuntu 22.10+)
    # that may not have happened yet.
    [[ -d /run/sshd ]] || run install -d -m 0755 /run/sshd

    if [[ "${FILE_CHANGED}" == "1" ]]; then
        # A config sshd cannot load only bites at its next start -- possibly a
        # reboot, locking the operator out -- so never leave one behind.
        if ! run sshd -t; then
            run rm -f "${SSHD_DROPIN}"
            sshd -t >/dev/null 2>&1 \
                || { notice "sshd's configuration was already invalid; left it unchanged."; return 0; }
            die "sshd rejected ${SSHD_DROPIN}; removed it again, sshd is unchanged."
        fi
        # Reloads a running sshd. A no-op while socket activation has not started
        # it yet; the next connection then reads the new file anyway.
        run systemctl try-reload-or-restart ssh \
            || notice "Could not reload ssh; the new MACs apply once sshd restarts."
    fi

    # Another drop-in that sorts first and sets MACs would win over ours.
    local macs weak_re=',(hmac-(sha1|md5)|umac-64)[^,]*,'
    macs="$(sshd -T 2>/dev/null | awk '$1 == "macs" {print $2; exit}' || true)"
    if [[ -z "${macs}" ]]; then
        notice "Could not read sshd's effective MACs; check with: sshd -T | grep '^macs '"
    elif [[ ",${macs}," =~ ${weak_re} ]]; then
        notice "sshd still offers weak MACs (${macs}): another sshd_config file sets MACs first."
    else
        ok "sshd MACs: ${macs}"
    fi
}
