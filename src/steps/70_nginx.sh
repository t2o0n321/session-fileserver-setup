#!/usr/bin/env bash
#
# nginx reverse proxy in front of the uWSGI socket, plus TLS.

# Session clients reach a file server through an exit service node that makes an
# outbound HTTPS request, so the endpoint should terminate TLS.  Four modes:
#   certbot      - Let's Encrypt via the nginx plugin (default, needs public DNS)
#   existing     - operator-provided cert/key paths
#   self-signed  - generated locally, for testing
#   none         - plain HTTP only
_provision_tls() {
    case "${TLS_MODE}" in
        none)        TLS_CERT=""; TLS_KEY=""; notice "Serving plain HTTP (--tls none)"; ;;
        existing)    TLS_CERT="${TLS_CERT_PATH}"; TLS_KEY="${TLS_KEY_PATH}"; ok "Using provided certificate"; ;;
        self-signed) _make_self_signed; ;;
        certbot)     : ;;  # handled after nginx is serving, below
    esac
}

_make_self_signed() {
    if [[ -f "${SELF_SIGNED_CERT}" && -f "${SELF_SIGNED_KEY}" ]]; then
        skipped "Self-signed certificate exists"
    else
        run openssl req -x509 -nodes -newkey rsa:2048 -days 3650 \
            -keyout "${SELF_SIGNED_KEY}" -out "${SELF_SIGNED_CERT}" \
            -subj "/CN=${DOMAIN}" -addext "subjectAltName=DNS:${DOMAIN}" \
            || die "Could not create a self-signed certificate."
        run chmod 640 "${SELF_SIGNED_KEY}"
        run chgrp "${WEB_GROUP}" "${SELF_SIGNED_KEY}"
        ok "Generated self-signed certificate"
    fi
    TLS_CERT="${SELF_SIGNED_CERT}"
    TLS_KEY="${SELF_SIGNED_KEY}"
}

# The proxy_pass block, shared by the HTTP-only and HTTPS server blocks.
# server_tokens is set in every server block rather than once in http{}:
# Ubuntu 26.04's nginx.conf already sets `server_tokens build;` there, and a
# second http-level setting fails `nginx -t`.
_location_block() {
    cat <<EOF
    client_max_body_size ${NGINX_MAX_BODY_SIZE};
    server_tokens off;

    location / {
        # Light per-source rate limit (defence-in-depth for the unauthenticated
        # POST /file). Onion traffic arrives via exit nodes, so the "source" is
        # the exit node, not the end user -- keep the rate generous.
        limit_req zone=sfs burst=30 nodelay;

        include uwsgi_params;
        uwsgi_pass unix:${SOCKET_PATH};
        uwsgi_read_timeout 60s;
        uwsgi_send_timeout 60s;
    }
EOF
}

_write_http_only_site() {
    write_file "${NGINX_AVAILABLE}" 0644 root:root <<EOF
# Generated by session-fileserver-setup ${INSTALLER_VERSION}.
server {
    listen 80;
    listen [::]:80;
    server_name ${DOMAIN};

$(_location_block)
}
EOF
}

# HTTP keeps a small location for the ACME challenge and otherwise redirects.
_write_https_site() {
    write_file "${NGINX_AVAILABLE}" 0644 root:root <<EOF
# Generated by session-fileserver-setup ${INSTALLER_VERSION}.
server {
    listen 80;
    listen [::]:80;
    server_name ${DOMAIN};
    server_tokens off;

    location /.well-known/acme-challenge/ { root /var/www/html; }
    location / { return 301 https://\$host\$request_uri; }
}

server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name ${DOMAIN};

    ssl_certificate     ${TLS_CERT};
    ssl_certificate_key ${TLS_KEY};
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_prefer_server_ciphers off;
    add_header Strict-Transport-Security "max-age=31536000" always;

$(_location_block)
}
EOF
}

# A catch-all default server that closes the connection, so the file server only
# answers for its own name and never for scans hitting the bare IP.
_write_default_server() {
    write_file "/etc/nginx/sites-available/000-${NGINX_SITE_NAME}-default" 0644 root:root <<EOF
# Generated by session-fileserver-setup ${INSTALLER_VERSION}.
server {
    listen 80 default_server;
    listen [::]:80 default_server;
    server_name _;
    server_tokens off;
    return 444;
}
EOF
    run ln -sfn "/etc/nginx/sites-available/000-${NGINX_SITE_NAME}-default" \
        "/etc/nginx/sites-enabled/000-${NGINX_SITE_NAME}-default"
}

_enable_site() {
    # Remove the distro default so it does not shadow our server_name.
    if [[ -e /etc/nginx/sites-enabled/default ]]; then
        run rm -f /etc/nginx/sites-enabled/default
        notice "Disabled the default nginx site"
    fi
    run ln -sfn "${NGINX_AVAILABLE}" "${NGINX_ENABLED}"
}

_reload_nginx() {
    run systemctl enable nginx >/dev/null 2>&1 || true
    if [[ "${DRY_RUN}" == "1" ]]; then
        printf '    %s[dry-run]%s nginx -t && systemctl reload nginx\n' "${C_DIM}" "${C_RESET}"
        return 0
    fi
    run nginx -t || die "nginx configuration test failed."
    run systemctl reload nginx 2>/dev/null || run systemctl restart nginx \
        || die "Could not (re)load nginx."
    ok "nginx configuration active"
}

# If ufw is already active before this installer's opt-in firewall step (e.g. the
# image or fail2ban enabled it), its default-deny blocks the ACME HTTP-01
# challenge on port 80 -- and later blocks Session exit nodes on 443. Open the web
# ports now, independently of --firewall, so certbot can succeed.
_open_web_ports_if_firewalled() {
    cmd_exists ufw || return 0
    ufw status 2>/dev/null | grep -q '^Status: active' || return 0
    run ufw allow 'Nginx Full' >/dev/null 2>&1 || true
    notice "ufw is active -- opened ports 80/443 (needed for the TLS challenge and for clients)."
}

_obtain_certbot_cert() {
    if [[ "${DRY_RUN}" == "1" ]]; then
        printf '    %s[dry-run]%s certbot --nginx -d %s\n' "${C_DIM}" "${C_RESET}" "${DOMAIN}"
        return 0
    fi
    # --hsts makes certbot add the same Strict-Transport-Security header to the
    # 443 block that _write_https_site writes. certbot applies it before
    # --redirect, so the port-80 block it splits off is a full copy of the site
    # and keeps _location_block's server_tokens off.
    local -a args=(--nginx -d "${DOMAIN}" --non-interactive --agree-tos --redirect --hsts)
    if [[ -n "${CERTBOT_EMAIL}" ]]; then
        args+=(-m "${CERTBOT_EMAIL}")
    else
        args+=(--register-unsafely-without-email)
    fi
    if certbot "${args[@]}"; then
        ok "Obtained a Let's Encrypt certificate for ${DOMAIN}"
        # certbot installs a systemd timer for renewal; make sure it is enabled.
        run systemctl enable --now certbot.timer >/dev/null 2>&1 || true
    else
        notice "certbot could not obtain a certificate. Its HTTP-01 challenge needs"
        notice "ports 80 AND 443 reachable from the internet (check any Vultr cloud"
        notice "firewall). The site is serving HTTP for now; once the ports are open,"
        notice "re-run:  certbot --nginx -d ${DOMAIN}"
    fi
}

# limit_req_zone must live in nginx's http{} context, so it goes in conf.d.
_write_limits_snippet() {
    write_file "/etc/nginx/conf.d/${NGINX_SITE_NAME}-limits.conf" 0644 root:root <<EOF
# Generated by session-fileserver-setup ${INSTALLER_VERSION}.
limit_req_zone \$binary_remote_addr zone=sfs:10m rate=20r/s;
EOF
}

step_nginx() {
    _write_limits_snippet
    _provision_tls
    _write_default_server
    # If a firewall is already up, make the web ports reachable now -- both for
    # certbot's challenge and for clients -- regardless of the opt-in --firewall step.
    _open_web_ports_if_firewalled
    if [[ "${TLS_MODE}" == "none" ]]; then
        _write_http_only_site
        _enable_site
        _reload_nginx
    elif [[ "${TLS_MODE}" == "certbot" ]]; then
        # Serve HTTP first so certbot's HTTP-01 challenge can be answered, then
        # let the plugin rewrite the site for 443.
        _write_http_only_site
        _enable_site
        _reload_nginx
        _obtain_certbot_cert
    else
        _write_https_site
        _enable_site
        _reload_nginx
    fi
}
