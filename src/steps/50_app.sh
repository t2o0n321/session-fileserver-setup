#!/usr/bin/env bash
#
# The Python virtualenv, the app config, and the server identity key.

# --system-site-packages so the venv can see python3-session-util, which is an
# apt package (there is no pip wheel for it).  The venv adds psycopg 3.x etc. on
# top -- explicitly not the distro's psycopg2.
_create_venv() {
    if [[ -x "${VENV_DIR}/bin/python3" ]]; then
        skipped "virtualenv exists at ${VENV_DIR}"
    else
        run python3 -m venv --system-site-packages "${VENV_DIR}" \
            || die "Could not create the virtualenv at ${VENV_DIR}"
        ok "Created virtualenv (system-site-packages)"
    fi
    run "${VENV_DIR}/bin/pip3" install --quiet --upgrade pip \
        || notice "Could not upgrade pip inside the venv (continuing)."
    run "${VENV_DIR}/bin/pip3" install --quiet "${PIP_PACKAGES[@]}" \
        || die "Could not install Python dependencies: ${PIP_PACKAGES[*]}"
    ok "Installed venv packages: ${PIP_PACKAGES[*]}"
    run chown -R root:root "${VENV_DIR}" || die "Could not set ownership on ${VENV_DIR}"
}

# The server's identity key lives in the private state directory, not in the code
# checkout's working directory.  The app resolves FILE_BASE_PATH and its key
# relative to its chdir, so the systemd unit sets WorkingDirectory to STATE_DIR.
#
# We generate the key here rather than letting the app create it on first start,
# for three reasons: it must be 0600 and owned by the service account; we want to
# show the operator the public key at the end; and if the app created it while
# running under www-data's umask the file could be group-readable.
_generate_server_key() {
    if [[ -f "${SERVER_KEY_FILE}" ]]; then
        skipped "Server identity key exists (preserved)"
    else
        if [[ "${DRY_RUN}" == "1" ]]; then
            printf '    %s[dry-run]%s generate Ed25519 server key at %s\n' "${C_DIM}" "${C_RESET}" "${SERVER_KEY_FILE}"
        else
            # Format expected by fileserver/crypto.py: 128 hex chars ==
            # 32-byte seed || 32-byte public key, one line.  Only the first 32
            # bytes are used as the signing seed; the rest is informational.
            local key_hex
            key_hex="$("${VENV_DIR}/bin/python3" - <<'PY'
from nacl.signing import SigningKey
sk = SigningKey.generate()
print(sk.encode().hex() + sk.verify_key.encode().hex())
PY
)" || die "Could not generate the server key."
            printf '%s\n' "${key_hex}" >"${SERVER_KEY_FILE}" || die "Could not write ${SERVER_KEY_FILE}"
            ok "Generated Ed25519 server identity key"
        fi
    fi
    run chmod 600 "${SERVER_KEY_FILE}" || die "Could not chmod ${SERVER_KEY_FILE}"
    run chown "${SERVICE_USER}:${SERVICE_GROUP}" "${SERVER_KEY_FILE}" \
        || die "Could not chown ${SERVER_KEY_FILE}"
}

# Derives the two hex public keys the client configuration needs.  The Ed25519
# pubkey is what this fork puts in DEFAULT_FILE_SERVER_ED25519_PUBKEY_HEX; the
# X25519 pubkey is what the onion-request layer actually encrypts to.
read_server_pubkeys() {
    [[ -f "${SERVER_KEY_FILE}" ]] || return 1
    "${VENV_DIR}/bin/python3" - "${SERVER_KEY_FILE}" <<'PY'
import sys
from nacl.signing import SigningKey
data = open(sys.argv[1]).read().strip()
seed = bytes.fromhex(data[:64])
sk = SigningKey(seed)
ed = sk.verify_key.encode().hex()
x = sk.to_curve25519_private_key().public_key.encode().hex()
print(ed)
print(x)
PY
}

# config.py is generated wholesale from our template rather than sed-patched into
# the sample, so it is deterministic and idempotent.  It imports the upstream
# base config and overrides only what this deployment changes.
_write_app_config() {
    write_file "${APP_CONFIG_FILE}" 0644 root:root <<EOF
# Generated by session-fileserver-setup ${INSTALLER_VERSION}. Edit deploy options
# via setup.sh flags and re-run; manual edits here are overwritten on re-run.
from .config_base import *

import logging
log_level = logging.INFO

# Local socket, peer-authenticated as the '${DB_USER}' OS/DB account.
pgsql_connect_opts = {
    "dbname": "${DB_NAME}",
    "user": "${DB_USER}",
}

# Absolute path in the service account's private state directory. The app only
# creates pool/prefix subdirectories, so this base directory must already exist.
FILE_BASE_PATH = "${FILES_DIR}"

# Matches this fork's client attachment limit (FileServerApis.MAX_FILE_SIZE).
MAX_FILE_SIZE = ${MAX_FILE_SIZE}
EOF
    if [[ "${FILE_CHANGED}" == "1" ]]; then
        ok "Wrote ${APP_CONFIG_FILE}"
    else
        skipped "${APP_CONFIG_FILE} already current"
    fi
}

step_app() {
    _create_venv
    _generate_server_key
    _write_app_config
}
